run_mode() {
  local mode="$1"
  local log="${OUT_DIR}/${mode}.log"
  local csv="${OUT_DIR}/${mode}-ps.csv"
  local screenshot="${OUT_DIR}/${mode}-window.png"
  local screenshot_assertion="${OUT_DIR}/${mode}-screenshot-assertion.log"
  local screenshot_status="${OUT_DIR}/${mode}-screenshot-status.txt"
  local popup_screenshot="${OUT_DIR}/${mode}-popup-window.png"
  local popup_screenshot_assertion="${OUT_DIR}/${mode}-popup-window-screenshot-assertion.log"
  local popup_screenshot_status="${OUT_DIR}/${mode}-popup-window-screenshot-status.txt"
  local ready_marker="${SKIKO_PICTURE_MARKER}"
  local assert_script="${ASSERT_SCRIPT}"
  local startup_marker="${APP_FRAME_MARKER}"
  local capture_marker="${APP_FRAME_MARKER}"

  if [[ "${JBR_SKIA_RENDER_MODE:-picture}" == "commands" ]]; then
    if [[ "${EXPECT_COMMAND_FALLBACK:-false}" == "true" ]]; then
      if [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-stream-invalid" ||
          "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "abi-mismatch" ||
          "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-capability-mismatch" ||
          "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "public-api-missing" ||
          "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-cache-clear-unavailable" ]]; then
        ready_marker="${FALLBACK_MARKER}"
      else
        ready_marker="${SKIKO_PICTURE_MARKER}"
      fi
      assert_script="${ASSERT_SCRIPT}"
    else
      ready_marker="${SKIKO_COMMAND_MARKER}"
      assert_script="${COMMAND_ASSERT_SCRIPT}"
    fi
  fi
  if [[ "${mode}" == "new" ]]; then
    startup_marker="${ready_marker}"
    capture_marker="${ready_marker}"
  fi

  printf 'timestamp,mode,pid,cpu_percent,rss_kb\n' > "${csv}"

  if [[ "${DRY_RUN:-false}" == "true" ]]; then
    echo "Would run Magic Jewel mode ${mode}" > "${log}"
    return
  fi

  launch_mode "${mode}" > "${log}" 2>&1 &

  local root_pid="$!"
  local startup_deadline=$(( $(date +%s) + STARTUP_TIMEOUT_SECONDS ))
  local end_time=0
  local sample_start_time=0
  local sample_start_line=0
  local sample_started=false
  local screenshot_done=false
  local popup_screenshot_done=false
  local profiler_path=""
  local profiler_pid=""
  local profiler_started=false

  profiler_path="$(resolve_asprof)"

  set +e
  while kill -0 "${root_pid}" 2>/dev/null; do
    local now
    now="$(date +%s)"
    if [[ "${end_time}" -eq 0 ]]; then
      if grep -q "${startup_marker}" "${log}" 2>/dev/null || [[ "${now}" -ge "${startup_deadline}" ]]; then
        sample_start_time=$(( now + WARMUP_SECONDS ))
        end_time=$(( sample_start_time + DURATION_SECONDS ))
      else
        sleep "${SAMPLE_INTERVAL_SECONDS}"
        continue
      fi
    fi
    [[ "${now}" -lt "${end_time}" ]] || break
    if [[ "${now}" -ge "${sample_start_time}" ]]; then
      if [[ "${sample_started}" == "false" ]]; then
        sample_start_line=$(( $(wc -l < "${log}" 2>/dev/null || echo 0) + 1 ))
        sample_started=true
        profiler_pid="$(app_pid)"
        start_profiler "${mode}" "${profiler_pid}" "${profiler_path}"
        profiler_started=true
      fi
      sample_process_tree "${mode}" "${root_pid}" "${csv}"
    fi
    if [[ ( "${mode}" == "new" || "${CAPTURE_OLD_SCREENSHOT}" == "true" )
        && "${screenshot_done}" == "false"
        && -x "${CAPTURE_SCRIPT}"
        && -x "${assert_script}"
        && $(grep -c "${capture_marker}" "${log}" 2>/dev/null) -gt 0 ]]; then
      if [[ "${MAGIC_JEWEL_POPUP_STRESS}" == "true" &&
          $(grep -c "${POPUP_SHOWN_MARKER}" "${log}" 2>/dev/null) -eq 0 ]]; then
        sleep "${SAMPLE_INTERVAL_SECONDS}"
        continue
      fi
      if [[ "${MAGIC_JEWEL_MENU_STRESS}" == "true" &&
          $(grep -c "${MENU_SHOWN_MARKER}" "${log}" 2>/dev/null) -eq 0 ]]; then
        sleep "${SAMPLE_INTERVAL_SECONDS}"
        continue
      fi
      if "${CAPTURE_SCRIPT}" "${CAPTURE_WINDOW_QUERY}" "${screenshot}" > "${OUT_DIR}/${mode}-capture.log" 2>&1; then
        if "${assert_script}" "${screenshot}" > "${screenshot_assertion}" 2>&1; then
          echo "passed" > "${screenshot_status}"
          screenshot_done=true
        fi
      fi
    fi
    if [[ "${mode}" == "new"
        && "${MAGIC_JEWEL_POPUP_WINDOW_STRESS}" == "true"
        && "${popup_screenshot_done}" == "false"
        && -x "${CAPTURE_SCRIPT}"
        && -x "${POPUP_WINDOW_ASSERT_SCRIPT}"
        && $(grep -c "${POPUP_WINDOW_SHOWN_MARKER}" "${log}" 2>/dev/null) -gt 0 ]]; then
      if "${CAPTURE_SCRIPT}" "${CAPTURE_POPUP_WINDOW_QUERY}" "${popup_screenshot}" > "${OUT_DIR}/${mode}-popup-window-capture.log" 2>&1; then
        if "${POPUP_WINDOW_ASSERT_SCRIPT}" "${popup_screenshot}" > "${popup_screenshot_assertion}" 2>&1; then
          echo "passed" > "${popup_screenshot_status}"
          popup_screenshot_done=true
        fi
      fi
    fi
    sleep "${SAMPLE_INTERVAL_SECONDS}"
  done

  if [[ ( "${mode}" == "new" || "${CAPTURE_OLD_SCREENSHOT}" == "true" )
      && "${screenshot_done}" == "false"
      && -x "${CAPTURE_SCRIPT}"
      && -x "${assert_script}"
      && $(grep -c "${capture_marker}" "${log}" 2>/dev/null) -gt 0 ]]; then
    if "${CAPTURE_SCRIPT}" "${CAPTURE_WINDOW_QUERY}" "${screenshot}" > "${OUT_DIR}/${mode}-capture.log" 2>&1; then
      if "${assert_script}" "${screenshot}" > "${screenshot_assertion}" 2>&1; then
        echo "passed" > "${screenshot_status}"
      fi
    fi
  fi

  if [[ "${profiler_started}" == "true" ]]; then
    stop_profiler "${mode}" "${profiler_pid}" "${profiler_path}"
  fi

  kill_process_tree "${root_pid}"
  wait "${root_pid}" >/dev/null 2>&1
  if [[ "${sample_start_line}" -gt 0 ]]; then
    {
      echo "${SAMPLE_BEGIN_MARKER} mode=${mode} warmupSeconds=${WARMUP_SECONDS}"
      tail -n +"${sample_start_line}" "${log}" 2>/dev/null || true
    } > "${OUT_DIR}/${mode}-sampled.log"
  else
    cp "${log}" "${OUT_DIR}/${mode}-sampled.log"
  fi
  set -e
}

summarize_csv() {
  local csv="$1"
  awk -F, '
    NR > 1 {
      key = $1 "," $2
      cpuBySample[key] += $4
      rssBySample[key] += $5
    }
    END {
      for (key in cpuBySample) {
        cpu += cpuBySample[key]
        rss += rssBySample[key]
        if (cpuBySample[key] > maxCpu) maxCpu = cpuBySample[key]
        if (rssBySample[key] > maxRss) maxRss = rssBySample[key]
        count++
      }
      if (count == 0) {
        printf "samples=0 avg_cpu=0 max_cpu=0 avg_rss_kb=0 max_rss_kb=0"
      } else {
        printf "samples=%d avg_cpu=%.2f max_cpu=%.2f avg_rss_kb=%.0f max_rss_kb=%.0f", count, cpu / count, maxCpu, rss / count, maxRss
      }
    }
  ' "${csv}"
}

csv_summary_field() {
  local csv="$1"
  local key="$2"
  if [[ ! -f "${csv}" ]]; then
    echo "0"
    return
  fi
  summarize_csv "${csv}" |
    tr ' ' '\n' |
    awk -F= -v key="${key}" '$1 == key { print $2; found = 1 } END { if (!found) print "0" }'
}

