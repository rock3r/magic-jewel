  [[ -n "${line}" ]] || return 0
  awk -v prefix="${key_prefix}" '
    {
      for (i = 2; i <= NF; i++) {
        split($i, value, "=")
        if (value[1] ~ /^[A-Za-z0-9_]+$/ && value[2] ~ /^-?[0-9]+$/) {
