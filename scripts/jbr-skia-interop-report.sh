validate_report() {
  local report="${OUT_DIR}/report.md"
  local mode="${JBR_SKIA_RENDER_MODE:-picture}"
  local expect_strict="${EXPECT_STRICT_COMMANDS:-true}"
  local failures=()
  local new_log="${OUT_DIR}/new-sampled.log"
  local new_full_log="${OUT_DIR}/new.log"
  [[ -f "${new_log}" ]] || new_log="${OUT_DIR}/new.log"
  [[ -f "${new_full_log}" ]] || new_full_log="${new_log}"

  if [[ "${mode}" == "commands" && "${expect_strict}" == "true" ]]; then
    local recorder_frames
    local skiko_command_frames
    local jbr_command_frames
    local skiko_picture_frames
    local jbr_picture_frames
    local screenshot_status
    local popup_screenshot_status

    recorder_frames="$(grep -c "${CMP_COMMAND_RECORDER_MARKER}" "${new_log}" 2>/dev/null || true)"
    skiko_command_frames="$(grep -c "${SKIKO_COMMAND_MARKER}" "${new_log}" 2>/dev/null || true)"
    jbr_command_frames="$(grep -c "${JBR_COMMAND_MARKER}" "${new_log}" 2>/dev/null || true)"
    skiko_picture_frames="$(grep -c "${SKIKO_PICTURE_MARKER}" "${new_log}" 2>/dev/null || true)"
    jbr_picture_frames="$(grep -c "${JBR_PICTURE_MARKER}" "${new_log}" 2>/dev/null || true)"
    screenshot_status="$(cat "${OUT_DIR}/new-screenshot-status.txt" 2>/dev/null || true)"
    popup_screenshot_status="$(cat "${OUT_DIR}/new-popup-window-screenshot-status.txt" 2>/dev/null || true)"

    [[ "${recorder_frames}" -gt 0 ]] || failures+=("no CMP command recorder frames")
    if [[ "${EXPECT_COMMAND_FALLBACK:-false}" == "true" ]]; then
      if [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-stream-invalid" ]]; then
        [[ "${skiko_command_frames}" -gt 0 ]] || failures+=("no Skiko command frames before invalid-stream fallback")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during invalid-stream fallback: ${jbr_command_frames}")
        if ! grep -q "${FALLBACK_MARKER} reason=command-stream-invalid" "${new_log}" 2>/dev/null &&
            ! grep -Eq "${SKIKO_COMMAND_MARKER}.*rendered=false" "${new_log}" 2>/dev/null; then
          failures+=("missing command-stream-invalid fallback marker or rendered=false command frame")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "abi-mismatch" ]]; then
        [[ "${skiko_command_frames}" -eq 0 ]] || failures+=("unexpected Skiko command frames during ABI-mismatch fallback: ${skiko_command_frames}")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during ABI-mismatch fallback: ${jbr_command_frames}")
        if ! grep -q "${FALLBACK_MARKER} reason=abi-mismatch" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing abi-mismatch fallback marker")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-capability-mismatch" ]]; then
        [[ "${skiko_command_frames}" -eq 0 ]] || failures+=("unexpected Skiko command frames during command-capability fallback: ${skiko_command_frames}")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during command-capability fallback: ${jbr_command_frames}")
        if ! grep -q "${FALLBACK_MARKER} reason=command-capability-mismatch" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing command-capability-mismatch fallback marker")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "native-abi-mismatch" ]]; then
        [[ "${skiko_command_frames}" -eq 0 ]] || failures+=("unexpected Skiko command frames during native-ABI fallback: ${skiko_command_frames}")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during native-ABI fallback: ${jbr_command_frames}")
        if ! grep -q "${FALLBACK_MARKER} reason=native-abi-mismatch" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing native-abi-mismatch fallback marker")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "public-api-missing" ]]; then
        [[ "${skiko_command_frames}" -eq 0 ]] || failures+=("unexpected Skiko command frames during public-API fallback: ${skiko_command_frames}")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during public-API fallback: ${jbr_command_frames}")
        if ! grep -q "${FALLBACK_MARKER} reason=public-api-missing" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing public-api-missing fallback marker")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "runtime-effect-compile-failed" ]]; then
        [[ "${skiko_command_frames}" -gt 0 ]] || failures+=("no Skiko command frames before RuntimeEffect compile fallback")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during RuntimeEffect compile fallback: ${jbr_command_frames}")
        if ! grep -q "${JBR_RUNTIME_EFFECT_COMPILE_FAILED_MARKER}" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing RuntimeEffect compile-failure marker")
        fi
        if ! grep -Eq "${SKIKO_COMMAND_MARKER}.*rendered=false" "${new_log}" 2>/dev/null; then
          failures+=("missing rendered=false command frame for RuntimeEffect compile fallback")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "runtime-effect-build-failed" ]]; then
        [[ "${skiko_command_frames}" -gt 0 ]] || failures+=("no Skiko command frames before RuntimeEffect build fallback")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during RuntimeEffect build fallback: ${jbr_command_frames}")
        if ! grep -q "${JBR_RUNTIME_EFFECT_BUILD_FAILED_MARKER}" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing RuntimeEffect build-failure marker")
        fi
        if [[ -n "${EXPECT_RUNTIME_EFFECT_BUILD_FAILURE_STAGE}" ]] &&
            ! grep -Eq "${JBR_RUNTIME_EFFECT_BUILD_FAILED_MARKER}.*stage=${EXPECT_RUNTIME_EFFECT_BUILD_FAILURE_STAGE}" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing RuntimeEffect build-failure stage marker: ${EXPECT_RUNTIME_EFFECT_BUILD_FAILURE_STAGE}")
        fi
        if ! grep -Eq "${SKIKO_COMMAND_MARKER}.*rendered=false" "${new_log}" 2>/dev/null; then
          failures+=("missing rendered=false command frame for RuntimeEffect build fallback")
        fi
      elif [[ "${EXPECT_COMMAND_FALLBACK_REASON:-}" == "command-cache-clear-unavailable" ]]; then
        if ! grep -q "${FALLBACK_MARKER} reason=command-cache-clear-unavailable" "${OUT_DIR}/new.log" 2>/dev/null; then
          failures+=("missing command-cache-clear-unavailable fallback marker")
        fi
      else
        [[ "${skiko_command_frames}" -eq 0 ]] || failures+=("unexpected Skiko command frames during expected fallback: ${skiko_command_frames}")
        [[ "${jbr_command_frames}" -eq 0 ]] || failures+=("unexpected JBR command frames during expected fallback: ${jbr_command_frames}")
        [[ "${skiko_picture_frames}" -gt 0 ]] || failures+=("no Skiko picture frames during expected fallback")
        [[ "${jbr_picture_frames}" -gt 0 ]] || failures+=("no JBR picture frames during expected fallback")
        if ! grep -Eq "(${CMP_COMMAND_RECORDER_MARKER}|${CMP_COMMAND_RECORDER_NESTED_MARKER}).*unsupported=[1-9][0-9]*.*${EXPECT_COMMAND_FALLBACK_REASON}=" "${new_log}" 2>/dev/null; then
          failures+=("CMP recorder did not report ${EXPECT_COMMAND_FALLBACK_REASON} as an unsupported command operation")
        fi
      fi
    else
      [[ "${skiko_command_frames}" -gt 0 ]] || failures+=("no Skiko command frames")
      [[ "${jbr_command_frames}" -gt 0 ]] || failures+=("no JBR command frames")
      local command_frame_delta=$(( skiko_command_frames - jbr_command_frames ))
      if [[ "${command_frame_delta}" -lt 0 ]]; then
        command_frame_delta=$(( -command_frame_delta ))
      fi
      local command_frame_max="${skiko_command_frames}"
      if [[ "${jbr_command_frames}" -gt "${command_frame_max}" ]]; then
        command_frame_max="${jbr_command_frames}"
      fi
      local command_frame_tolerance=$(( (command_frame_max + 99) / 100 ))
      if [[ "${command_frame_tolerance}" -lt 3 ]]; then
        command_frame_tolerance=3
      fi
      [[ "${command_frame_delta}" -le "${command_frame_tolerance}" ]] ||
        failures+=("Skiko/JBR command frame count mismatch: ${skiko_command_frames}/${jbr_command_frames} tolerance=${command_frame_tolerance}")
      [[ "${skiko_picture_frames}" -eq 0 ]] || failures+=("unexpected Skiko picture frames in strict command mode: ${skiko_picture_frames}")
      [[ "${jbr_picture_frames}" -eq 0 ]] || failures+=("unexpected JBR picture frames in strict command mode: ${jbr_picture_frames}")
      if grep -Eq "(${CMP_COMMAND_RECORDER_MARKER}|${CMP_COMMAND_RECORDER_NESTED_MARKER}).*unsupported=[1-9][0-9]*" "${new_log}" 2>/dev/null; then
        failures+=("CMP recorder reported unsupported command operations")
      fi
      if [[ "${EXPECT_MIN_TEXT_COMMANDS}" -gt 0 ]]; then
        local max_text_commands
        max_text_commands="$(max_command_recorder_field "${new_log}" "textCommands")"
        [[ "${max_text_commands}" -ge "${EXPECT_MIN_TEXT_COMMANDS}" ]] ||
          failures+=("CMP recorder max textCommands ${max_text_commands} below expected ${EXPECT_MIN_TEXT_COMMANDS}")
      fi
      if [[ "${EXPECT_MIN_PARAGRAPH_TEXT_COMMANDS}" -gt 0 ]]; then
        local max_paragraph_text_commands
        max_paragraph_text_commands="$(max_command_recorder_field "${new_log}" "paragraphTextCommands")"
        [[ "${max_paragraph_text_commands}" -ge "${EXPECT_MIN_PARAGRAPH_TEXT_COMMANDS}" ]] ||
          failures+=("CMP recorder max paragraphTextCommands ${max_paragraph_text_commands} below expected ${EXPECT_MIN_PARAGRAPH_TEXT_COMMANDS}")
      fi
      if [[ "${EXPECT_MIN_IMAGE_REFS}" -gt 0 ]]; then
        local max_image_refs
        max_image_refs="$(max_command_recorder_field "${new_log}" "imageRefs")"
        [[ "${max_image_refs}" -ge "${EXPECT_MIN_IMAGE_REFS}" ]] ||
          failures+=("CMP recorder max imageRefs ${max_image_refs} below expected ${EXPECT_MIN_IMAGE_REFS}")
      fi
      if [[ "${EXPECT_MIN_IMAGE_CACHE_CLEARS}" -gt 0 ]]; then
        local max_image_cache_clears
        max_image_cache_clears="$(max_command_recorder_field "${new_log}" "imageCacheClears")"
        [[ "${max_image_cache_clears}" -ge "${EXPECT_MIN_IMAGE_CACHE_CLEARS}" ]] ||
          failures+=("CMP recorder max imageCacheClears ${max_image_cache_clears} below expected ${EXPECT_MIN_IMAGE_CACHE_CLEARS}")
      fi
      if [[ "${EXPECT_MIN_IMAGE_CACHE_EVICTS}" -gt 0 ]]; then
        local max_image_cache_evicts
        max_image_cache_evicts="$(max_command_recorder_field "${new_log}" "imageCacheEvicts")"
        [[ "${max_image_cache_evicts}" -ge "${EXPECT_MIN_IMAGE_CACHE_EVICTS}" ]] ||
          failures+=("CMP recorder max imageCacheEvicts ${max_image_cache_evicts} below expected ${EXPECT_MIN_IMAGE_CACHE_EVICTS}")
      fi
      if [[ "${EXPECT_MAX_IMAGE_DEFINES}" -ge 0 ]]; then
        local max_image_defines
        max_image_defines="$(max_command_recorder_field "${new_log}" "imageDefines")"
        [[ "${max_image_defines}" -le "${EXPECT_MAX_IMAGE_DEFINES}" ]] ||
          failures+=("CMP recorder max imageDefines ${max_image_defines} above expected ${EXPECT_MAX_IMAGE_DEFINES}")
      fi
      if [[ "${EXPECT_MAX_IMAGE_CACHE_CLEARS}" -ge 0 ]]; then
        local max_image_cache_clears
        max_image_cache_clears="$(max_command_recorder_field "${new_log}" "imageCacheClears")"
        [[ "${max_image_cache_clears}" -le "${EXPECT_MAX_IMAGE_CACHE_CLEARS}" ]] ||
          failures+=("CMP recorder max imageCacheClears ${max_image_cache_clears} above expected ${EXPECT_MAX_IMAGE_CACHE_CLEARS}")
      fi
      if [[ "${EXPECT_MIN_JBR_IMAGE_CACHE_CLEARS}" -gt 0 ]]; then
        local jbr_image_cache_clears
        jbr_image_cache_clears="$(grep -c "${JBR_IMAGE_CACHE_CLEAR_MARKER}" "${new_log}" 2>/dev/null || true)"
        [[ "${jbr_image_cache_clears}" -ge "${EXPECT_MIN_JBR_IMAGE_CACHE_CLEARS}" ]] ||
          failures+=("JBR image cache clear markers ${jbr_image_cache_clears} below expected ${EXPECT_MIN_JBR_IMAGE_CACHE_CLEARS}")
      fi
      if [[ "${EXPECT_MIN_JBR_SCOPED_IMAGE_CACHE_CLEARS}" -gt 0 ]]; then
        local jbr_scoped_image_cache_clears
        jbr_scoped_image_cache_clears="$(grep -Ec "${JBR_IMAGE_CACHE_CLEAR_MARKER}.*contextId=0x" "${new_log}" 2>/dev/null || true)"
        [[ "${jbr_scoped_image_cache_clears}" -ge "${EXPECT_MIN_JBR_SCOPED_IMAGE_CACHE_CLEARS}" ]] ||
          failures+=("JBR scoped image cache clear markers ${jbr_scoped_image_cache_clears} below expected ${EXPECT_MIN_JBR_SCOPED_IMAGE_CACHE_CLEARS}")
      fi
      if [[ "${EXPECT_MIN_JBR_IMAGE_CACHE_EVICTS}" -gt 0 ]]; then
        local jbr_image_cache_evicts
        jbr_image_cache_evicts="$(grep -c "${JBR_IMAGE_CACHE_EVICT_MARKER}" "${new_log}" 2>/dev/null || true)"
        [[ "${jbr_image_cache_evicts}" -ge "${EXPECT_MIN_JBR_IMAGE_CACHE_EVICTS}" ]] ||
          failures+=("JBR image cache evict markers ${jbr_image_cache_evicts} below expected ${EXPECT_MIN_JBR_IMAGE_CACHE_EVICTS}")
      fi

      if [[ "${EXPECT_MIN_JBR_SHADOW_COMMANDS}" -gt 0 ]]; then
        local max_shadow_commands
        max_shadow_commands="$(max_jbr_command_timing_field "${new_log}" "shadowCommands")"
        [[ "${max_shadow_commands%.*}" -ge "${EXPECT_MIN_JBR_SHADOW_COMMANDS}" ]] ||
          failures+=("JBR shadow commands ${max_shadow_commands} below expected ${EXPECT_MIN_JBR_SHADOW_COMMANDS}")
      fi

      if [[ "${EXPECT_MIN_JBR_EFFECT_HANDLE_DEFINES}" -gt 0 ]]; then
        local jbr_effect_handle_defines
        jbr_effect_handle_defines="$(grep -c "${JBR_EFFECT_HANDLE_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_effect_handle_defines}" -ge "${EXPECT_MIN_JBR_EFFECT_HANDLE_DEFINES}" ]] ||
          failures+=("JBR effect handle define markers ${jbr_effect_handle_defines} below expected ${EXPECT_MIN_JBR_EFFECT_HANDLE_DEFINES}")
      fi
      if [[ "${EXPECT_MIN_JBR_EFFECT_HANDLE_USES}" -gt 0 ]]; then
        local jbr_effect_handle_uses
        jbr_effect_handle_uses="$(grep -c "${JBR_EFFECT_HANDLE_USE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_effect_handle_uses}" -ge "${EXPECT_MIN_JBR_EFFECT_HANDLE_USES}" ]] ||
          failures+=("JBR effect handle use markers ${jbr_effect_handle_uses} below expected ${EXPECT_MIN_JBR_EFFECT_HANDLE_USES}")
      fi
      if [[ "${EXPECT_MIN_JBR_EFFECT_HANDLE_EVICTS}" -gt 0 ]]; then
        local jbr_effect_handle_evicts
        jbr_effect_handle_evicts="$(grep -c "${JBR_EFFECT_HANDLE_EVICT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_effect_handle_evicts}" -ge "${EXPECT_MIN_JBR_EFFECT_HANDLE_EVICTS}" ]] ||
          failures+=("JBR effect handle evict markers ${jbr_effect_handle_evicts} below expected ${EXPECT_MIN_JBR_EFFECT_HANDLE_EVICTS}")
      fi
      if [[ "${EXPECT_MIN_JBR_EFFECT_HANDLE_CACHE_HITS}" -gt 0 ]]; then
        local jbr_effect_handle_cache_hits
        jbr_effect_handle_cache_hits="$(grep -c "${JBR_EFFECT_HANDLE_CACHE_HIT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_effect_handle_cache_hits}" -ge "${EXPECT_MIN_JBR_EFFECT_HANDLE_CACHE_HITS}" ]] ||
          failures+=("JBR effect handle cache-hit markers ${jbr_effect_handle_cache_hits} below expected ${EXPECT_MIN_JBR_EFFECT_HANDLE_CACHE_HITS}")
      fi
      if [[ "${EXPECT_MIN_JBR_SHADER_HANDLE_DEFINES}" -gt 0 ]]; then
        local jbr_shader_handle_defines
        jbr_shader_handle_defines="$(grep -c "${JBR_SHADER_HANDLE_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_shader_handle_defines}" -ge "${EXPECT_MIN_JBR_SHADER_HANDLE_DEFINES}" ]] ||
          failures+=("JBR shader handle define markers ${jbr_shader_handle_defines} below expected ${EXPECT_MIN_JBR_SHADER_HANDLE_DEFINES}")
      fi
      if [[ "${EXPECT_MIN_JBR_SHADER_HANDLE_USES}" -gt 0 ]]; then
        local jbr_shader_handle_uses
        jbr_shader_handle_uses="$(grep -c "${JBR_SHADER_HANDLE_USE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_shader_handle_uses}" -ge "${EXPECT_MIN_JBR_SHADER_HANDLE_USES}" ]] ||
          failures+=("JBR shader handle use markers ${jbr_shader_handle_uses} below expected ${EXPECT_MIN_JBR_SHADER_HANDLE_USES}")
      fi
      if [[ "${EXPECT_MIN_JBR_SHADER_HANDLE_EVICTS}" -gt 0 ]]; then
        local jbr_shader_handle_evicts
        jbr_shader_handle_evicts="$(grep -c "${JBR_SHADER_HANDLE_EVICT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_shader_handle_evicts}" -ge "${EXPECT_MIN_JBR_SHADER_HANDLE_EVICTS}" ]] ||
          failures+=("JBR shader handle evict markers ${jbr_shader_handle_evicts} below expected ${EXPECT_MIN_JBR_SHADER_HANDLE_EVICTS}")
      fi
      if [[ "${EXPECT_MIN_JBR_SHADER_HANDLE_CACHE_HITS}" -gt 0 ]]; then
        local jbr_shader_handle_cache_hits
        jbr_shader_handle_cache_hits="$(grep -c "${JBR_SHADER_HANDLE_CACHE_HIT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_shader_handle_cache_hits}" -ge "${EXPECT_MIN_JBR_SHADER_HANDLE_CACHE_HITS}" ]] ||
          failures+=("JBR shader handle cache-hit markers ${jbr_shader_handle_cache_hits} below expected ${EXPECT_MIN_JBR_SHADER_HANDLE_CACHE_HITS}")
      fi
      if [[ "${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_HITS}" -gt 0 ]]; then
        local jbr_runtime_effect_cache_hits
        jbr_runtime_effect_cache_hits="$(grep -c "${JBR_RUNTIME_EFFECT_CACHE_HIT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_runtime_effect_cache_hits}" -ge "${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_HITS}" ]] ||
          failures+=("JBR RuntimeEffect source-cache hit markers ${jbr_runtime_effect_cache_hits} below expected ${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_HITS}")
      fi
      if [[ "${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_EVICTS}" -gt 0 ]]; then
        local jbr_runtime_effect_cache_evicts
        if [[ -n "${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE}" ]]; then
          if [[ "${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE}" != "shader" &&
                "${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE}" != "colorFilter" ]]; then
            failures+=("Unsupported EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE ${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE}")
          fi
          jbr_runtime_effect_cache_evicts="$(grep -Ec "${JBR_RUNTIME_EFFECT_CACHE_EVICT_MARKER}.*type=${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE}( |$)" "${new_full_log}" 2>/dev/null || true)"
        else
          jbr_runtime_effect_cache_evicts="$(grep -c "${JBR_RUNTIME_EFFECT_CACHE_EVICT_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        fi
        [[ "${jbr_runtime_effect_cache_evicts}" -ge "${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_EVICTS}" ]] ||
          failures+=("JBR RuntimeEffect source-cache evict markers ${jbr_runtime_effect_cache_evicts} below expected ${EXPECT_MIN_JBR_RUNTIME_EFFECT_CACHE_EVICTS} for type ${EXPECT_JBR_RUNTIME_EFFECT_CACHE_EVICT_TYPE:-any}")
      fi
      if [[ "${EXPECT_MIN_JBR_FONT_DATA_DEFINES}" -gt 0 ]]; then
        local jbr_font_data_defines
        jbr_font_data_defines="$(grep -c "${JBR_FONT_DATA_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_font_data_defines}" -ge "${EXPECT_MIN_JBR_FONT_DATA_DEFINES}" ]] ||
          failures+=("JBR font-data define markers ${jbr_font_data_defines} below expected ${EXPECT_MIN_JBR_FONT_DATA_DEFINES}")
      fi
      if [[ "${EXPECT_MAX_JBR_FONT_DATA_DEFINES}" -ge 0 ]]; then
        local jbr_font_data_defines
        jbr_font_data_defines="$(grep -c "${JBR_FONT_DATA_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_font_data_defines}" -le "${EXPECT_MAX_JBR_FONT_DATA_DEFINES}" ]] ||
          failures+=("JBR font-data define markers ${jbr_font_data_defines} above expected ${EXPECT_MAX_JBR_FONT_DATA_DEFINES}")
      fi
      if [[ "${EXPECT_MAX_JBR_EFFECT_HANDLE_DEFINES}" -ge 0 ]]; then
        local jbr_effect_handle_defines
        jbr_effect_handle_defines="$(grep -c "${JBR_EFFECT_HANDLE_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_effect_handle_defines}" -le "${EXPECT_MAX_JBR_EFFECT_HANDLE_DEFINES}" ]] ||
          failures+=("JBR effect handle define markers ${jbr_effect_handle_defines} above expected ${EXPECT_MAX_JBR_EFFECT_HANDLE_DEFINES}")
      fi
      if [[ "${EXPECT_MAX_JBR_SHADER_HANDLE_DEFINES}" -ge 0 ]]; then
        local jbr_shader_handle_defines
        jbr_shader_handle_defines="$(grep -c "${JBR_SHADER_HANDLE_DEFINE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_shader_handle_defines}" -le "${EXPECT_MAX_JBR_SHADER_HANDLE_DEFINES}" ]] ||
          failures+=("JBR shader handle define markers ${jbr_shader_handle_defines} above expected ${EXPECT_MAX_JBR_SHADER_HANDLE_DEFINES}")
      fi
      if [[ "${EXPECT_MAX_JBR_RUNTIME_EFFECT_CACHE_MISSES}" -ge 0 ]]; then
        local jbr_runtime_effect_cache_misses
        jbr_runtime_effect_cache_misses="$(grep -c "${JBR_RUNTIME_EFFECT_CACHE_MISS_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${jbr_runtime_effect_cache_misses}" -le "${EXPECT_MAX_JBR_RUNTIME_EFFECT_CACHE_MISSES}" ]] ||
          failures+=("JBR RuntimeEffect source-cache miss markers ${jbr_runtime_effect_cache_misses} above expected ${EXPECT_MAX_JBR_RUNTIME_EFFECT_CACHE_MISSES}")
      fi
      if [[ "${EXPECT_MIN_POPUP_FRAMES}" -gt 0 ]]; then
        local popup_frames
        popup_frames="$(grep -c "${POPUP_FRAME_MARKER}" "${new_log}" 2>/dev/null || true)"
        [[ "${popup_frames}" -ge "${EXPECT_MIN_POPUP_FRAMES}" ]] ||
          failures+=("Swing popup paint markers ${popup_frames} below expected ${EXPECT_MIN_POPUP_FRAMES}")
      fi
      if [[ "${EXPECT_MIN_APP_NEW_FRAMES}" -gt 0 ]]; then
        local app_new_frames
        app_new_frames="$(grep -c "${APP_FRAME_MARKER}" "${new_log}" 2>/dev/null || true)"
        [[ "${app_new_frames}" -ge "${EXPECT_MIN_APP_NEW_FRAMES}" ]] ||
          failures+=("Magic Jewel Compose frame markers ${app_new_frames} below expected ${EXPECT_MIN_APP_NEW_FRAMES}")
      fi
      if [[ "${EXPECT_MIN_TINY_FULL_SCENE_INJECTIONS}" -gt 0 ]]; then
        local tiny_full_scene_injections
        tiny_full_scene_injections="$(grep -c "${SKIKO_TINY_FULL_SCENE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${tiny_full_scene_injections}" -ge "${EXPECT_MIN_TINY_FULL_SCENE_INJECTIONS}" ]] ||
          failures+=("Skiko tiny FullScene injection markers ${tiny_full_scene_injections} below expected ${EXPECT_MIN_TINY_FULL_SCENE_INJECTIONS}")
      fi
      if [[ "${MAGIC_JEWEL_POPUP_WINDOW_STRESS}" == "true" ]]; then
        if ! grep -q "${POPUP_WINDOW_SHOWN_MARKER}" "${new_full_log}" 2>/dev/null; then
          failures+=("missing Swing popup window shown marker")
        fi
        [[ "${popup_screenshot_status}" == "passed" ]] || failures+=("popup window screenshot assertion did not pass")
      fi
      if [[ "${MAGIC_JEWEL_MENU_STRESS}" == "true" ]]; then
        if ! grep -q "${MENU_SHOWN_MARKER}" "${new_full_log}" 2>/dev/null; then
          failures+=("missing Swing menu shown marker")
        fi
      fi
      if [[ "${EXPECT_MIN_SURFACE_CHANGES}" -gt 0 ]]; then
        local surface_changes
        surface_changes="$(grep -c "${SKIKO_SURFACE_CHANGE_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${surface_changes}" -ge "${EXPECT_MIN_SURFACE_CHANGES}" ]] ||
          failures+=("Skiko surface-change markers ${surface_changes} below expected ${EXPECT_MIN_SURFACE_CHANGES}")
      fi
      if [[ "${EXPECT_MIN_COMMAND_CACHE_CLEARS}" -gt 0 ]]; then
        local command_cache_clears
        command_cache_clears="$(grep -c "${SKIKO_COMMAND_CACHES_CLEARED_MARKER}" "${new_full_log}" 2>/dev/null || true)"
        [[ "${command_cache_clears}" -ge "${EXPECT_MIN_COMMAND_CACHE_CLEARS}" ]] ||
          failures+=("Skiko command-cache clear markers ${command_cache_clears} below expected ${EXPECT_MIN_COMMAND_CACHE_CLEARS}")
      fi
      if [[ -n "${EXPECT_SURFACE_CONTEXT_CHANGED}" ]]; then
        if ! grep -Eq "${SKIKO_SURFACE_CHANGE_MARKER}.*contextChanged=${EXPECT_SURFACE_CONTEXT_CHANGED}" "${new_full_log}" 2>/dev/null; then
          failures+=("missing Skiko surface-change marker with contextChanged=${EXPECT_SURFACE_CONTEXT_CHANGED}")
        fi
      fi
      if [[ -n "${EXPECT_SURFACE_CHANGED}" ]]; then
        if ! grep -Eq "${SKIKO_SURFACE_CHANGE_MARKER}.*surfaceChanged=${EXPECT_SURFACE_CHANGED}" "${new_full_log}" 2>/dev/null; then
          failures+=("missing Skiko surface-change marker with surfaceChanged=${EXPECT_SURFACE_CHANGED}")
        fi
      fi
    fi
    if [[ -n "${EXPECT_COMMAND_FALLBACK_MARKER}" ]] &&
        ! grep -Fq -- "${EXPECT_COMMAND_FALLBACK_MARKER}" "${new_full_log}" 2>/dev/null; then
      failures+=("missing expected new-log marker: ${EXPECT_COMMAND_FALLBACK_MARKER}")
    fi
    local screenshot_status_required="true"
    if [[ "${EXPECT_COMMAND_FALLBACK:-false}" == "true" ]]; then
      case "${EXPECT_COMMAND_FALLBACK_REASON:-}" in
        abi-mismatch|command-cache-clear-unavailable|command-capability-mismatch|command-stream-invalid|native-abi-mismatch|public-api-missing|runtime-effect-compile-failed|runtime-effect-build-failed)
          screenshot_status_required="false"
          ;;
      esac
    fi
    if [[ "${screenshot_status_required}" == "true" ]]; then
      [[ "${screenshot_status}" == "passed" ]] || failures+=("screenshot assertion did not pass")
    fi
  fi

  {
    echo
    echo "## Validation"
    echo
    if [[ "${#failures[@]}" -eq 0 ]]; then
      echo "- status: passed"
    else
      echo "- status: failed"
      for failure in "${failures[@]}"; do
        echo "- ${failure}"
      done
    fi
  } >> "${report}"

  if [[ "${#failures[@]}" -eq 0 ]]; then
    write_machine_summary "passed"
  else
    write_machine_summary "failed" "${failures[@]}"
  fi

  if [[ "${#failures[@]}" -ne 0 ]]; then
    printf 'Strict command validation failed; see %s\n' "${report}" >&2
    return 1
  fi
}

