        imageDefines / frames, maxImageDefines, imageRefs / frames, maxImageRefs,
        imageCacheClears / frames, maxImageCacheClears, imageCacheEvicts / frames, maxImageCacheEvicts,
        reasonSummary
    }
  ' "${log}"
