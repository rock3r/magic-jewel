  awk -v marker="${CMP_COMMAND_RECORDER_MARKER}" -v duration="${DURATION_SECONDS}" '
    index($0, marker) {
      frames++
      frameUnsupported = 0
      for (i = 1; i <= NF; i++) {
        split($i, value, "=")
        if (value[1] == "commands") {
          commands += value[2]
          if (value[2] > maxCommands) maxCommands = value[2]
        } else if (value[1] == "unsupported") {
          frameUnsupported = value[2]
          unsupported += value[2]
          if (value[2] > maxUnsupported) maxUnsupported = value[2]
        } else if (value[1] == "textCommands") {
          textCommands += value[2]
          if (value[2] > maxTextCommands) maxTextCommands = value[2]
        } else if (value[1] == "paragraphTextCommands") {
          paragraphTextCommands += value[2]
          if (value[2] > maxParagraphTextCommands) maxParagraphTextCommands = value[2]
        } else if (value[1] == "imageDefines") {
          imageDefines += value[2]
